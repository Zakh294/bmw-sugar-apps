#!/usr/bin/env python3
"""data/cameras.json -> everything built from it:

    apps/speedcam_ua/cameras.js   the app's offline database (a plain Node module)
    data/cameras.geojson          for any GIS tool / map
    data/cameras.csv              for a spreadsheet, or Google My Maps (import: "lat", "lon" columns)
    data/cameras.kml              Google My Maps / Google Earth / Organic Maps, one folder per region
    data/cameras.gpx              Organic Maps, OsmAnd, Garmin and most navigators (waypoints)

    python3 tools/gen_app_data.py
"""
import csv, json, os
from xml.sax.saxutils import escape

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = json.load(open(os.path.join(ROOT, 'data', 'cameras.json'), encoding='utf-8'))
meta, cams = src['meta'], src['cameras']


def label(c):
    if c['road']:
        return '%s, %s км (%s)' % (c['road'], c['km'], c['place'])
    return '%s, %s' % (c['place'], c['region'])


# --- the app's module ---
rows = [[c['id'], c['lat'], c['lon'], c['limit'], c['road'] or '', c['km'] or '', c['region'], c['place']] for c in cams]
with open(os.path.join(ROOT, 'apps', 'speedcam_ua', 'cameras.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write("'use strict';\n")
    f.write('// Generated by tools/gen_app_data.py from data/cameras.json - do not edit by hand.\n')
    f.write('// Source: %s (fetched %s). Rows: [id, lat, lon, limit km/h, road, km, region, place]\n' % (meta['source'], meta['fetched']))
    f.write('module.exports = {\n    meta: %s,\n    rows: [\n' % json.dumps(meta, ensure_ascii=False))
    for r in rows:
        f.write('        %s,\n' % json.dumps(r, ensure_ascii=False))
    f.write('    ],\n};\n')

# --- GeoJSON ---
gj = {'type': 'FeatureCollection', 'name': 'speedcams_ua', 'meta': meta, 'features': [
    {'type': 'Feature', 'geometry': {'type': 'Point', 'coordinates': [c['lon'], c['lat']]},
     'properties': dict((k, c[k]) for k in ('id', 'limit', 'road', 'km', 'region', 'place', 'type'))} for c in cams]}
json.dump(gj, open(os.path.join(ROOT, 'data', 'cameras.geojson'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

# --- CSV ---
with open(os.path.join(ROOT, 'data', 'cameras.csv'), 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f)
    w.writerow(['id', 'lat', 'lon', 'limit_kmh', 'road', 'km', 'region', 'place', 'name'])
    for c in cams:
        w.writerow([c['id'], c['lat'], c['lon'], c['limit'], c['road'] or '', c['km'] or '', c['region'], c['place'],
                    'Камера %s км/год - %s' % (c['limit'], label(c))])

# --- KML (one folder per region) ---
regions = {}
for c in cams:
    regions.setdefault(c['region'], []).append(c)
k = ['<?xml version="1.0" encoding="UTF-8"?>', '<kml xmlns="http://www.opengis.net/kml/2.2"><Document>',
     '<name>Камери автофіксації України (%d, %s)</name>' % (len(cams), meta['fetched']),
     '<description>%s</description>' % escape(meta['source'])]
for lim, col in ((50, 'ff1f1fe1'), (70, 'ff0080ff'), (90, 'ff00b4ff'), (110, 'ff00d2ff')):
    k.append('<Style id="cam%d"><IconStyle><color>%s</color><scale>1.1</scale><Icon><href>'
             'http://maps.google.com/mapfiles/kml/shapes/camera.png</href></Icon></IconStyle></Style>' % (lim, col))
for reg in sorted(regions):
    k.append('<Folder><name>%s</name>' % escape(reg))
    for c in regions[reg]:
        k.append('<Placemark><name>%s</name><description>%s</description><styleUrl>#cam%d</styleUrl>'
                 '<Point><coordinates>%f,%f,0</coordinates></Point></Placemark>'
                 % (escape('%s км/год' % c['limit']), escape(label(c)), c['limit'] if c['limit'] in (50, 70, 90, 110) else 50,
                    c['lon'], c['lat']))
    k.append('</Folder>')
k.append('</Document></kml>')
open(os.path.join(ROOT, 'data', 'cameras.kml'), 'w', encoding='utf-8').write('\n'.join(k) + '\n')

# --- GPX waypoints ---
g = ['<?xml version="1.0" encoding="UTF-8"?>',
     '<gpx version="1.1" creator="speedcam-ua" xmlns="http://www.topografix.com/GPX/1/1">',
     '<metadata><name>Камери автофіксації України</name><desc>%s</desc></metadata>' % escape(meta['source'])]
for c in cams:
    g.append('<wpt lat="%f" lon="%f"><name>%s</name><desc>%s</desc><sym>Speed Camera</sym><type>speed_camera</type></wpt>'
             % (c['lat'], c['lon'], escape('Камера %s' % c['limit']), escape(label(c))))
g.append('</gpx>')
open(os.path.join(ROOT, 'data', 'cameras.gpx'), 'w', encoding='utf-8').write('\n'.join(g) + '\n')

print('%d cameras -> cameras.js, .geojson, .csv, .kml, .gpx' % len(cams))
